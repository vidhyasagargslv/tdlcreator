// TDL generator (shared by index.html and examples build)
function genTDL(o){
 const E=o.entities||[], L=[], P=s=>L.push(s);
 const q=s=>String(s||'').replace(/"/g,"'");
 const V={Sales:'Sales',Purchases:'Purchase',SalesOrders:'Sales Order',PurchaseOrders:'Purchase Order',Receipts:'Receipt',Payments:'Payment'};
 P(';; ===== Generated by TDL Maker on '+new Date().toISOString().slice(0,10)+' =====');
 P(';; Menu: '+o.menuName+' | Config: '+(o.config?'Yes':'No')+' | Dates: '+(o.dates?'Yes':'No'));
 P(';; Push: '+(E.join(', ')||'none')+' | Format: '+o.format+' | Pull (experimental): '+(o.pull?'Yes':'No'));
 P(';; URL template: '+o.url);
 P(';; Load via F1 > TDL & Add-On > Manage Local TDLs.  UNTESTED on real TallyPrime - verify first.');
 P('');
 P('[#Menu: Gateway of Tally]');
 P('    Add: Key Item: At End: '+o.menuName+': '+o.menuKey+': Menu: TS Sync Menu');
 P('');
 P('[Menu: TS Sync Menu]');
 P('    Title: "'+q(o.menuName)+'"');
 if(o.config) P('    Key Item: Configuration: C: Display: TS Config');
 if(o.dates)  P('    Key Item: Set Date Range: D: Display: TS Dates');
 E.forEach((e,i)=>P('    Key Item: Push '+e+': '+(i+1)+': Call: TS Push '+e));
 if(o.pull) P('    Key Item: Pull from URL (Experimental): P: Display: TS Pull Report');
 P('    Item: Blank');
 P('    Key Item: @@locQuit: Q: Menu Quit');
 P('');
 // variables
 const vars=[['TSApiURL',o.url],['TSApiKey',o.apiKey],['TSCompanyCode',o.company]];
 vars.forEach(([n])=>{P('[Variable: '+n+']');P('    Type: String');P('    Persistent: Yes');P('');});
 if(o.dates){['TSFromDate','TSToDate'].forEach(n=>{P('[Variable: '+n+']');P('    Type: Date');P('    Persistent: Yes');P('');});}
 P('[System: Variable]');
 vars.forEach(([n,v])=>P('    '+n+': "'+q(v)+'"'));
 if(o.dates){P('    TSFromDate: '+(o.fromDefault==='fy'?'$$YearStart:##SVCurrentDate':'$$MonthStart:##SVCurrentDate'));P('    TSToDate: $$MonthEnd:##SVCurrentDate');}
 P('');
 // URL formula with placeholders
 let f='"'+q(o.url)+'"';
 const rep=(tok,expr)=>{f=f.split(tok).join('" + '+expr+' + "');};
 rep('{company}','##TSCompanyCode'); rep('{companyname}','##SVCurrentCompany');
 rep('{fromdate}',o.dates?'$$String:##TSFromDate:UniversalDate':'$$String:##SVFromDate:UniversalDate');
 rep('{todate}',o.dates?'$$String:##TSToDate:UniversalDate':'$$String:##SVToDate:UniversalDate');
 P('[System: Formula]');
 P('    TSBaseURL: '+f.replace(/ \+ ""/g,'').replace(/"" \+ /g,''));
 P('');
 // config / date screens
 const screen=(name,title,fields)=>{
  P('[Report: '+name+']');P('    Form: '+name);P('    Title: "'+title+'"');
  fields.forEach(x=>P('    Variable: '+x[0]));P('');
  P('[Form: '+name+']');P('    Part: '+name);P('    Width: 70% Screen');P('');
  P('[Part: '+name+']');P('    Lines: '+fields.map(x=>name+' '+x[0]).join(', '));P('');
  fields.forEach(([v,lab,t])=>{
   P('[Line: '+name+' '+v+']');P('    Fields: Medium Prompt, '+name+' '+v+' Fld');P('    Local: Field: Medium Prompt: Info: "'+lab+'"');P('');
   P('[Field: '+name+' '+v+' Fld]');P('    Use: '+(t==='d'?'Uni Date Field':'Name Field'));
   if(t!=='d')P('    Max: 250');P('    Set As: ##'+v);P('    Modifies: '+v+': Yes');P('');
  });
 };
 if(o.config) screen('TS Config','Sync Configuration',[['TSApiURL','API URL'],['TSApiKey','API Key'],['TSCompanyCode','Company Code']]);
 if(o.dates)  screen('TS Dates','Sync Date Range',[['TSFromDate','From Date','d'],['TSToDate','To Date','d']]);
 const fromE=o.dates?'##TSFromDate':'##SVFromDate', toE=o.dates?'##TSToDate':'##SVToDate';
 const enc=o.format==='JSON'?'UTF8':'ASCII';
 E.forEach(e=>{
  const isV=!!V[e], col='TS Col '+e, rep='TS Req '+e;
  P('[Function: TS Push '+e+']');
  P('    00: HTTP Post: @@TSBaseURL + "/'+e.toLowerCase()+'": '+enc+': '+rep+': TS Resp Err: TS Resp Ok');
  P('');
  P('[Collection: '+col+']');
  if(isV){P('    Type: Voucher');P('    Fetch: *.*');P('    Filter: TS Flt '+e+', TS Flt Date');}
  else {P('    Type: '+(e==='Ledgers'?'Ledger':'Stock Item'));P('    Fetch: *.*');}
  P('');
  if(isV){P('[System: Formula]');P('    TS Flt '+e+': $$IsSysNameEqual:'+V[e].replace(/ /g,'')+':$VoucherTypeName OR $$IsVchTypeOf:$VoucherTypeName:"'+V[e]+'"');P('');}
  P('[Report: '+rep+']');P('    Form: '+rep);P('    Export: Yes');
  if(o.format==='JSON')P('    JSONTag: "'+e.toLowerCase()+'"');
  P('    Variable: SVExportFormat');P('    Set: SVExportFormat: $$SysName:'+(o.format==='JSON'?'JSONEx':'XML'));P('');
  P('[Form: '+rep+']');P('    Part: '+rep);P('    XMLTag: "ENVELOPE"');P('');
  P('[Part: '+rep+']');P('    Line: '+rep+' Hdr, '+rep+' Row');P('    Repeat: '+rep+' Row: '+col);P('    Scroll: Vertical');P('');
  P('[Line: '+rep+' Hdr]');P('    Fields: TS Hdr Company, TS Hdr Key, TS Hdr From, TS Hdr To');P('');
  P('[Line: '+rep+' Row]');P('    XMLTag: "'+(isV?'VOUCHER':'MASTER')+'"');
  P('    Fields: '+(isV?'TS F Date, TS F VchNo, TS F VchType, TS F Party, TS F Amount, TS F GUID':'TS F Name, TS F Parent, TS F GUID'));P('');
 });
 if(E.length){
  const fl=[['TS Hdr Company','COMPANY','##TSCompanyCode'],['TS Hdr Key','APIKEY','##TSApiKey'],['TS Hdr From','FROMDATE','$$String:'+fromE+':UniversalDate'],['TS Hdr To','TODATE','$$String:'+toE+':UniversalDate'],
   ['TS F Date','DATE','$$String:$Date:UniversalDate'],['TS F VchNo','VOUCHERNUMBER','$VoucherNumber'],['TS F VchType','VOUCHERTYPE','$VoucherTypeName'],['TS F Party','PARTYNAME','$PartyLedgerName'],['TS F Amount','AMOUNT','$$String:$Amount'],['TS F GUID','GUID','$GUID'],['TS F Name','NAME','$Name'],['TS F Parent','PARENT','$Parent']];
  fl.forEach(([n,t,s])=>{P('[Field: '+n+']');P('    Use: Name Field');P('    Set As: '+s);P('    XMLTag: "'+t+'"');P('');});
  P('[System: Formula]');P('    TS Flt Date: $Date >= '+fromE+' AND $Date <= '+toE);P('');
  P('[Report: TS Resp Ok]');P('    Form: TS Resp');P('    Title: "Sync Successful"');P('');
  P('[Report: TS Resp Err]');P('    Form: TS Resp');P('    Title: "Sync Failed"');P('');
  P('[Form: TS Resp]');P('    Part: TS Resp');P('');P('[Part: TS Resp]');P('    Line: TS Resp');P('');
  P('[Line: TS Resp]');P('    Field: TS Resp');P('');P('[Field: TS Resp]');P('    Use: Name Field');P('    Set As: $$String:$RESPONSE');P('    Full Width: Yes');P('');
 }
 if(o.pull){
  P(';; EXPERIMENTAL pull: reads remote XML <ENVELOPE><ROW><NAME/><VALUE/></ROW></ENVELOPE>');
  P('[Collection: TS Pull Col]');P('    RemoteURL: @@TSBaseURL + "/pull"');P('    XMLObjectPath: ROW: 1: ENVELOPE');P('    Fetch: NAME, VALUE');P('');
  P('[Report: TS Pull Report]');P('    Form: TS Pull Report');P('    Title: "Remote Data (Experimental)"');P('');
  P('[Form: TS Pull Report]');P('    Part: TS Pull Report');P('');
  P('[Part: TS Pull Report]');P('    Line: TS Pull Line');P('    Repeat: TS Pull Line: TS Pull Col');P('    Scroll: Vertical');P('');
  P('[Line: TS Pull Line]');P('    Fields: TS Pull Name, TS Pull Value');P('');
  P('[Field: TS Pull Name]');P('    Use: Name Field');P('    Set As: $NAME');P('');
  P('[Field: TS Pull Value]');P('    Use: Name Field');P('    Set As: $VALUE');P('');
 }
 return L.join('\r\n')+'\r\n';
}
function validateTDL(t){
 const err=[];const known=/^(Add|Title|Key Item|Item|Type|Persistent|Form|Variable|Part|Width|Lines?|Local|Fields?|Use|Max|Set As|Set|Modifies|Fetch|Filter|Export|JSONTag|XMLTag|Repeat|Scroll|Full Width|RemoteURL|XMLObjectPath|\d\d|TS[\w ]*)$/;
 t.split(/\r?\n/).forEach((l,i)=>{const s=l.trim();if(!s||s.startsWith(';;'))return;
  if(s.startsWith('[')){if(!/^\[[#!]?[A-Za-z ]+:[^\[\]]+\]$/.test(s))err.push('Line '+(i+1)+': bad header');return;}
  const k=s.split(':')[0].trim();if(!known.test(k))err.push('Line '+(i+1)+': unknown attribute "'+k+'"');
  if((s.match(/"/g)||[]).length%2)err.push('Line '+(i+1)+': unbalanced quotes');});
 return err;
}
if(typeof module!=='undefined')module.exports={genTDL,validateTDL};
